from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak, KeepTogether
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from xml.sax.saxutils import escape
from pathlib import Path
out=Path('output/pdf/FoodBank_Online_Demo_Testing_Guide.pdf')
s=getSampleStyleSheet()
s.add(ParagraphStyle(name='DocTitle',fontName='Helvetica-Bold',fontSize=25,leading=29,spaceAfter=14,textColor=colors.HexColor('#173f35')))
s.add(ParagraphStyle(name='SectionTitle',fontName='Helvetica-Bold',fontSize=13,leading=17,spaceBefore=13,spaceAfter=5,textColor=colors.HexColor('#173f35')))
s.add(ParagraphStyle(name='Copy',fontName='Helvetica',fontSize=10.5,leading=14,spaceAfter=6))
s.add(ParagraphStyle(name='Step',parent=s['Copy'],leftIndent=13,firstLineIndent=-13,spaceAfter=3))
s.add(ParagraphStyle(name='Result',parent=s['Copy'],textColor=colors.HexColor('#245e4f'),spaceBefore=4))
a=[]
def p(t,style='Copy'):a.append(Paragraph(t,s[style]))
def h(t):p(t,'SectionTitle')
def steps(items):
 for i,t in enumerate(items,1):p(f'{i}. {t}','Step')
def result(t):p('<b>Expected result:</b> '+t,'Result')
p('FoodBank Online Demo<br/>Testing Guide','DocTitle')
p('Thank you for trying FoodBank. Explore how a foodbank team records deliveries, distributes food, and checks available stock.')
p('<b>Use fictional information only.</b> Other testers may be using the same demo, so quantities and records can change while you work.')
h('1  Sign in')
p('Open the demo link provided with this guide. Sign in using the username and password supplied to you.')
p('<b>Volunteer:</b> receive food, distribute food, adjust stock, and check stock and product totals.<br/><b>Manager:</b> all volunteer tasks, plus stock history, catalogue setup, and permitted account management.<br/><b>Super Admin:</b> broader account management alongside stock and catalogue tasks.')
p('The Dashboard is your starting page. Use the navigation menu to open each task. On a phone, open the menu first.')
h('2  Find an item')
p('Open <b>Stock items</b> and search for a product or brand. Choose one item and note its product, brand, package size, and available packages. Different package sizes appear separately.')
p('<b>Count whole packages.</b> For three bags of rice weighing 1 kg each, enter <b>3</b>, not 3,000.')
h('3  Record a delivery')
steps(['Open <b>Receive stock</b> and search for the item you chose.','Enter <b>3</b> packages and add the item to the receipt.','Add a note such as "Demo delivery test."','Select <b>Save receipt</b> and wait for the success message.','Return to <b>Stock items</b> and find the same item.'])
result('Stock increases by three packages, unless another tester also changes it.')
p('Adding an item to the receipt list does not save it. Stock changes only after the receipt saves successfully.')
h('4  Distribute food')
steps(['Open <b>Distribute food</b> and select a fictional demo household.','Select a stock item with available stock and add <b>1</b> package.','Review the household and item, then select <b>Save distribution</b>.','Wait for success, then check the item\'s stock again.'])
result('Stock decreases by one package.')
p('For real operations, confirm appointments outside FoodBank. Appointment booking is not included in this version.')
a.append(PageBreak())
p('Continue testing','DocTitle')
h('5  Correct a stock count')
steps(['Open <b>Stock adjustment</b> and find an item with available stock.','Choose to remove <b>1</b> package.','Enter "Demo damaged package test" as the reason.','Check the new balance preview and save.'])
result('Stock decreases by one package.')
p('Enter the amount to add or remove, rather than the final balance you want.')
h('6  Explore totals and history')
p('Open <b>Product totals</b>, search for a product, and expand its row.')
result('You can see its combined quantity and the individual stock items behind it.')
p('Managers and Super Admins can also open <b>Stock history</b> to find the receipt, distribution, or adjustment they recorded.')
h('7  Try a mistake')
p('Try submitting an empty form or distributing more packages than are available.')
result('The app explains the problem and prevents an invalid save.')
p('Also try the demo on your phone. Check whether you can find the menu, read the forms, and reach table buttons by scrolling sideways.')
h('8  Send your feedback')
p('For each problem, send the following details:')
for t in ['<b>Page:</b> where it happened.','<b>Steps:</b> what you clicked or entered.','<b>Expected result:</b> what you thought would happen.','<b>Actual result:</b> what happened instead.','<b>Device:</b> phone or computer, and browser.','<b>Screenshot:</b> if it helps explain the problem.']:p('- '+t,'Step')
p('Please also mention anything confusing, even if it technically worked.')
h('Demo limits')
p('This version does not include appointment booking, adding households through the interface, full household management, or the wider volunteer module.')
p('Saved stock changes cannot be edited or deleted. Report an incorrect entry so a correction can be recorded clearly.')
p('When finished, open the menu beside your name and select <b>Log out</b>.')
def footer(c,d):
 c.setFont('Helvetica',8);c.setFillColor(colors.HexColor('#64746e'))
 c.drawString(42,25,'FoodBank | Online demo testing guide')
 c.drawRightString(A4[0]-42,25,str(d.page))
SimpleDocTemplate(str(out),pagesize=A4,rightMargin=42,leftMargin=42,topMargin=35,bottomMargin=42,title='FoodBank Online Demo Testing Guide',author='FoodBank').build(a,onFirstPage=footer,onLaterPages=footer)
print(out.resolve())
